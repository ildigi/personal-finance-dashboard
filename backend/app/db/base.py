"""Base dichiarativa, convenzioni dei nomi e tipi di colonna condivisi.

Convenzioni (SPEC §10):
- chiave primaria `id BIGINT GENERATED BY DEFAULT AS IDENTITY`;
- `created_at` / `updated_at` TIMESTAMPTZ su tutte le tabelle;
- importi `NUMERIC(14,2)`, quantità `NUMERIC(20,8)`, cambi `NUMERIC(20,10)`;
- valute `CHAR(3)`; enum come `TEXT` + `CHECK`.
"""

from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from enum import StrEnum
from typing import Annotated, Any

from sqlalchemy import (
    CHAR,
    BigInteger,
    CheckConstraint,
    DateTime,
    Identity,
    MetaData,
    Numeric,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_N_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# --- Tipi annotati -----------------------------------------------------------
Money = Annotated[Decimal, mapped_column(Numeric(14, 2))]
Quantity = Annotated[Decimal, mapped_column(Numeric(20, 8))]
UnitPrice = Annotated[Decimal, mapped_column(Numeric(20, 8))]
Rate = Annotated[Decimal, mapped_column(Numeric(20, 10))]
Currency = Annotated[str, mapped_column(CHAR(3))]
Str = Annotated[str, mapped_column(Text)]
JsonDict = Annotated[dict[str, Any], mapped_column(JSONB)]


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {  # noqa: RUF012
        str: Text,
        datetime: DateTime(timezone=True),
        dict[str, Any]: JSONB,
    }


class IdMixin:
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True, sort_order=-100)


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(server_default=func.now(), sort_order=100)
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), onupdate=func.now(), sort_order=100
    )


def check_in(column: str, values: type[StrEnum] | tuple[str, ...]) -> CheckConstraint:
    """`CHECK (column IN (...))`, chiamato `ck_<tabella>_<column>_valid`."""
    allowed = tuple(v.value for v in values) if isinstance(values, type) else values
    quoted = ", ".join(f"'{v}'" for v in allowed)
    return CheckConstraint(f"{column} IN ({quoted})", name=f"{column}_valid")


def check_currency(column: str) -> CheckConstraint:
    return CheckConstraint(f"{column} ~ '^[A-Z]{{3}}$'", name=f"{column}_iso4217")
